"""Kaggle driver: unpacks the bundled repo, then builds, tests and benchmarks it.

Generated by kaggle/make_kernel.py, which fills in MODE and BUNDLE.
Everything worth keeping lands in /kaggle/working (results/, logs/).
"""

import base64
import io
import os
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

MODE = "__MODE__"
BUNDLE = "__BUNDLE__"

WORK = Path("/kaggle/working")
SRC = Path("/tmp/cuda-vector-search")
LOGS = WORK / "logs"
RESULTS = WORK / "results"
T0 = time.time()


def step(name, cmd, timeout=1800, env=None):
    LOGS.mkdir(parents=True, exist_ok=True)
    t = time.time()
    print(f"\n### {name}  (t+{t - T0:.0f}s)\n$ {cmd}", flush=True)
    with open(LOGS / f"{name}.log", "w") as log:
        try:
            p = subprocess.run(cmd, shell=True, cwd=SRC, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                               text=True, timeout=timeout, env={**os.environ, **(env or {})})
            out, rc = p.stdout, p.returncode
        except subprocess.TimeoutExpired as e:
            out, rc = (e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or ""), "timeout"
        log.write(out)
    tail = "\n".join(out.splitlines()[-40:])
    print(tail, flush=True)
    print(f"### {name} -> rc={rc} in {time.time() - t:.0f}s", flush=True)
    return rc


def main():
    if SRC.exists():
        shutil.rmtree(SRC)
    SRC.mkdir(parents=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
        tf.extractall(SRC)
    RESULTS.mkdir(parents=True, exist_ok=True)
    py = sys.executable

    step("env", "nvidia-smi; nvcc --version; " + py + " -c 'import torch;print(torch.__version__, torch.version.cuda)'")
    step("pip_build_deps", f"{py} -m pip install -q ninja pytest")
    rc = step("build", f"{py} -c 'from cuda_vector_search import _ext; _ext.load(verbose=True); print(\"BUILD OK\")'",
              timeout=900)
    step("pytest", f"{py} -m pytest -q -rA tests", timeout=900)
    if rc != 0:
        print("build failed, stopping")
        return

    if MODE == "smoke":
        step("sweep", f"{py} bench/sweep.py --n 1000000 --d 384 --out {RESULTS}/sweep.json", timeout=900)
        step("sweep768", f"{py} bench/sweep.py --n 1000000 --d 768 --out {RESULTS}/sweep768.json", timeout=900)

        gpu_args = "--sizes 100000,1000000 --dims 384 --batches 1,32,256 --ks 10,100"
        base_args = "--sizes 100000 --dims 384 --batches 1,32,256 --ks 10,100"
    else:
        gpu_args = ""
        base_args = ""
    step("bench_gpu", f"{py} bench/bench_gpu.py {gpu_args} --out {RESULTS}/gpu.json", timeout=1200)

    if MODE == "full":
        if step("pip_faiss_gpu", f"{py} -m pip install -q faiss-gpu-cu12") != 0 or \
           step("faiss_check", f"{py} -c 'import faiss; n=faiss.get_num_gpus(); print(\"gpus\", n); assert n > 0'") != 0:
            step("pip_faiss_cpu", f"{py} -m pip install -q faiss-cpu")
        step("bench_baselines", f"{py} bench/bench_baselines.py {base_args} --out {RESULTS}/baselines.json",
             timeout=1200)

    inputs = " ".join(str(p) for p in [RESULTS / "gpu.json", RESULTS / "baselines.json"] if p.exists())
    if inputs:
        step("report", f"{py} bench/report.py {inputs} --out {RESULTS}/t4.json")

    if MODE != "full":
        print(f"\nall done in {time.time() - T0:.0f}s")
        return
    step("rag_demo",
         f"{py} -m pip install -q sentence-transformers >/dev/null 2>&1; "
         f"{py} examples/rag_search.py build examples/sample_docs --out /tmp/rag_index && "
         f"{py} examples/rag_search.py ask /tmp/rag_index 'why does my bread go stale in the fridge?' -k 2 && "
         f"{py} examples/rag_search.py ask /tmp/rag_index 'what should I do about a squeaky chain' -k 2 && "
         f"{py} examples/rag_search.py ask /tmp/rag_index 'how thick are the rings of saturn' -k 2",
         timeout=600)
    print(f"\nall done in {time.time() - T0:.0f}s")


if __name__ == "__main__":
    main()
